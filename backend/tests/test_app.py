# ── Missing API Key ───────────────────────────────────────────

class TestMissingAPIKey:
    def test_sarvam_service_fails_without_key(self):
        """Service should raise clear error when key is missing."""
        import app.services.sarvam_service as svc
        old_client = svc._client
        svc._client = None
        # Patch the settings instance's sarvam_api_key field directly
        original_key = get_settings().sarvam_api_key
        # Use object.__setattr__ to bypass pydantic protection on the cached singleton
        try:
            object.__setattr__(get_settings(), 'sarvam_api_key', '')
            with pytest.raises(RuntimeError, match="SARVAM_API_KEY"):
                svc._get_client()
        finally:
            object.__setattr__(get_settings(), 'sarvam_api_key', original_key)
            svc._client = old_client


