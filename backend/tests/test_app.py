# ── PDF Text Extraction ───────────────────────────────────────

class TestPDFExtraction:
    def test_extract_creates_pages(self):
        """Test extraction with a real minimal PDF generated by PyMuPDF."""
        import fitz
        # Create a minimal PDF in memory and save to bytes
        doc = fitz.open()
        page = doc.new_page()
        page.insert_text((72, 72), "Quantum Mechanics Chapter 1\n\nThe wave-particle duality is fundamental.")
        page2 = doc.new_page()
        page2.insert_text((72, 72), "Chapter 2: Schrodinger Equation\n\nThe time-dependent equation is...")
        pdf_bytes = doc.tobytes()
        doc.close()

        # Write to a new temp file (not opened by fitz)
        import tempfile, os
        fd, tmp_name = tempfile.mkstemp(suffix=".pdf")
        try:
            os.close(fd)
            Path(tmp_name).write_bytes(pdf_bytes)
            result = extract_text_from_pdf(Path(tmp_name))
            assert result["page_count"] == 2
            assert len(result["pages"]) == 2
            assert "Quantum" in result["pages"][0]["text"]
            assert result["is_scanned"] is False
        finally:
            os.unlink(tmp_name)


# ── Chunking ──────────────────────────────────────────────────

class TestChunking:
    def test_basic_chunking(self):
        pages = [
            {"page_number": 1, "text": "This is paragraph one about physics.\n\nThis is paragraph two about quantum mechanics.", "headings": ["Physics"]},
            {"page_number": 2, "text": "Another page of content about semiconductors.", "headings": []},
        ]
        chunks = chunk_document("doc1", pages)
        assert len(chunks) >= 1
        assert all(c.document_id == "doc1" for c in chunks)
        assert all(c.page_number in (1, 2) for c in chunks)

    def test_empty_page_skipped(self):
        pages = [
            {"page_number": 1, "text": "", "headings": []},
            {"page_number": 2, "text": "Content here.", "headings": []},
        ]
        chunks = chunk_document("doc2", pages)
        assert all(c.page_number == 2 for c in chunks)

    def test_chunk_metadata_preserved(self):
        pages = [
            {"page_number": 5, "text": "Important content about band theory in semiconductors.", "headings": ["Band Theory"]},
        ]
        chunks = chunk_document("doc3", pages)
        assert chunks[0].page_number == 5
        assert chunks[0].heading == "Band Theory"
        assert chunks[0].char_count > 0


# ── Retrieval ─────────────────────────────────────────────────

class TestRetrieval:
    def test_add_and_search(self):
        idx = LocalVectorIndex()
        chunks = [
            DocumentChunk(chunk_id="c1", document_id="d1", page_number=1,
                         content="The Schrödinger equation describes quantum state evolution."),
            DocumentChunk(chunk_id="c2", document_id="d1", page_number=2,
                         content="Semiconductor band theory explains conductivity."),
            DocumentChunk(chunk_id="c3", document_id="d2", page_number=1,
                         content="Machine learning uses neural networks for classification."),
        ]
        idx.add_chunks(chunks)

        results = idx.search("quantum mechanics", top_k=2)
        assert len(results) >= 1
        # Top result should be about quantum / Schrödinger
        assert "quantum" in results[0][0].content.lower() or "schrödinger" in results[0][0].content.lower()

    def test_filter_by_document(self):
        idx = LocalVectorIndex()
        chunks = [
            DocumentChunk(chunk_id="c1", document_id="d1", page_number=1,
                         content="Quantum physics fundamentals and wave equations."),
            DocumentChunk(chunk_id="c2", document_id="d2", page_number=1,
                         content="Quantum computing uses qubits for computation."),
        ]
        idx.add_chunks(chunks)

        results = idx.search("quantum", document_ids=["d2"])
        assert all(r[0].document_id == "d2" for r in results)

    def test_remove_document(self):
        idx = LocalVectorIndex()
        chunks = [
            DocumentChunk(chunk_id="c1", document_id="d1", page_number=1, content="Test content A."),
            DocumentChunk(chunk_id="c2", document_id="d1", page_number=2, content="Test content B."),
        ]
        idx.add_chunks(chunks)
        removed = idx.remove_document("d1")
        assert removed == 2
        assert idx.total_chunks == 0


